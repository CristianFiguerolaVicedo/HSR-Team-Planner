-- Accounts (login with Discord / Google) and each user's "My characters".
-- Only what the app shows is stored: no email, no OAuth tokens.

CREATE TABLE users (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider      VARCHAR(20)  NOT NULL,              -- "discord" | "google"
    provider_id   VARCHAR(64)  NOT NULL,              -- the user's id at that provider
    name          VARCHAR(100) NOT NULL,
    avatar_url    VARCHAR(300),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT users_provider_account UNIQUE (provider, provider_id)
);

CREATE TABLE user_roster (
    user_id       BIGINT  NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    character_id  INTEGER NOT NULL REFERENCES characters (id),
    eidolon       INTEGER NOT NULL CHECK (eidolon BETWEEN 0 AND 6),
    PRIMARY KEY (user_id, character_id)
);
