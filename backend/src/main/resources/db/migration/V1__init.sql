CREATE TABLE characters (
    id             INTEGER      PRIMARY KEY,          -- game id, e.g. 1005
    name           VARCHAR(80)  NOT NULL UNIQUE,
    rarity         INTEGER      NOT NULL CHECK (rarity BETWEEN 4 AND 5),
    element        VARCHAR(20)  NOT NULL,
    path           VARCHAR(20)  NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    base_spd       DOUBLE PRECISION NOT NULL,
    variant_group  VARCHAR(40),
    icon_url       VARCHAR(300),
    mini_icon_url  VARCHAR(300),
    synced_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE light_cones (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hsrwiki_id  INTEGER,
    name        VARCHAR(120) NOT NULL UNIQUE,
    rarity      INTEGER      NOT NULL CHECK (rarity BETWEEN 3 AND 5),
    path        VARCHAR(20)  NOT NULL,
    icon_url    VARCHAR(300),
    synced_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE synergies (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_a_id  INTEGER     NOT NULL REFERENCES characters (id),
    character_b_id  INTEGER     NOT NULL REFERENCES characters (id),
    score           INTEGER     NOT NULL CHECK (score > 0),
    source          VARCHAR(20) NOT NULL,
    reason          VARCHAR(500),
    CONSTRAINT synergies_ordered_pair CHECK (character_a_id < character_b_id),
    CONSTRAINT synergies_unique_pair UNIQUE (character_a_id, character_b_id, source)
);

CREATE INDEX synergies_character_b_idx ON synergies (character_b_id);

-- Teams: shared by link -----------------------------------------------------------------------

CREATE TABLE teams (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    share_code  VARCHAR(8)   NOT NULL UNIQUE,
    name        VARCHAR(60)  NOT NULL,
    game_mode   VARCHAR(30),
    notes       VARCHAR(500),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE team_slots (
    id               BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id          BIGINT  NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
    position         INTEGER NOT NULL CHECK (position BETWEEN 0 AND 3),
    character_id     INTEGER NOT NULL REFERENCES characters (id),
    light_cone_id    BIGINT  REFERENCES light_cones (id),
    eidolon          INTEGER NOT NULL CHECK (eidolon BETWEEN 0 AND 6),
    superimposition  INTEGER CHECK (superimposition BETWEEN 1 AND 5),
    spd              DOUBLE PRECISION CHECK (spd > 0),
    CONSTRAINT team_slots_unique_position UNIQUE (team_id, position)
);

CREATE INDEX team_slots_team_idx ON team_slots (team_id);
